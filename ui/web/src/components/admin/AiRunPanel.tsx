'use client';
import { useState } from 'react';

type Mode = 'ai' | 'heuristic';

/**
 * Run-panel shared across every /admin/ai/<skill> page.
 *
 * Defaults: heuristic-only — the rule-based version of the skill runs
 * locally with no API key. AI is opt-in per-page (set `aiAllowed`) and
 * is only worth turning on for skills where the LLM adds free-text
 * generation that rules can't do well (drafting replies, summarising
 * unstructured notes).
 */
export function AiRunPanel<T>({
  skill,
  render,
  buttonLabel = 'Run',
  description,
  aiAllowed = false,
}: {
  skill: string;
  render: (data: T) => React.ReactNode;
  buttonLabel?: string;
  description?: string;
  /** When true, also expose the LLM-powered version as a secondary button. */
  aiAllowed?: boolean;
}) {
  const [busy, setBusy] = useState(false);
  const [mode, setMode] = useState<Mode | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<T | null>(null);
  const [resultMode, setResultMode] = useState<Mode | null>(null);
  const [usage, setUsage] = useState<any>(null);

  async function run(m: Mode) {
    setBusy(true); setMode(m); setError(null); setResult(null); setUsage(null);
    try {
      const res = await fetch(`/api/admin/ai/${skill}?mode=${m}`, { method: 'POST' });
      const data = await res.json();
      if (!res.ok) { setError(data.error ?? `Request failed (${res.status})`); return; }
      setResult(data as T);
      setResultMode(m);
      if (data.usage) setUsage(data.usage);
    } catch (e: any) {
      setError(e?.message ?? 'Failed to run analysis');
    } finally {
      setBusy(false); setMode(null);
    }
  }

  return (
    <div className="space-y-4">
      <div className="card p-6 space-y-4">
        {description && <p className="text-sm text-brand-700">{description}</p>}

        <div className="flex flex-wrap gap-3 items-center">
          {/* Primary: deterministic, instant, no key */}
          <button onClick={() => run('heuristic')} disabled={busy} className="btn-primary">
            {busy && mode === 'heuristic' ? '⚡ Running…' : `⚡ ${buttonLabel}`}
          </button>

          {/* Opt-in: LLM version, only on pages where it adds value */}
          {aiAllowed && (
            <button onClick={() => run('ai')} disabled={busy} className="btn-outline">
              {busy && mode === 'ai' ? '🤖 Thinking…' : '✨ Run with AI (slower, nuanced)'}
            </button>
          )}
        </div>

        <div className="text-xs text-brand-700/70 space-y-0.5">
          <p>
            <b>⚡ Rule-based:</b> deterministic Python logic — same data, same output, every time. Instant, no API key.
          </p>
          {aiAllowed && (
            <p>
              <b>✨ AI:</b> uses OpenAI GPT-4o for free-text generation (summaries, drafted replies). Takes ~5–20s. Requires <span className="font-mono">OPENAI_API_KEY</span>.
            </p>
          )}
        </div>
      </div>

      {error && (
        <div className="card p-4 bg-rose-50/40 border-rose-300">
          <div className="text-xs uppercase tracking-widest text-rose-700 mb-1">Error</div>
          <div className="text-sm text-rose-800">{error}</div>
        </div>
      )}

      {busy && !result && (
        <div className="card p-8 text-center">
          <div className="animate-pulse text-brand-700">
            {mode === 'ai' ? '🤖 GPT-4o is drafting…' : '⚡ Crunching the numbers…'}
          </div>
        </div>
      )}

      {result && (
        <>
          <div className={`card p-2 px-4 text-xs flex items-center justify-between ${
            resultMode === 'ai' ? 'bg-brand-50' : 'bg-amber-50/50 border-amber-200'
          }`}>
            <span className="text-brand-700">
              {resultMode === 'ai'
                ? '✨ Generated by GPT-4o'
                : '⚡ Rule-based result — deterministic, re-runnable'}
            </span>
            <button onClick={() => { setResult(null); setResultMode(null); setUsage(null); }}
                    className="text-xs text-brand-700 hover:text-gold-600 underline">
              Clear
            </button>
          </div>

          {render(result)}

          {usage && resultMode === 'ai' && (
            <div className="text-xs text-brand-700/60 text-right">
              Tokens — input: {usage.input?.toLocaleString()} ·
              output: {usage.output?.toLocaleString()}
              {usage.cacheRead > 0 && ` · cache hit: ${usage.cacheRead.toLocaleString()}`}
            </div>
          )}
        </>
      )}
    </div>
  );
}

export function Pill({ tone, children }: { tone: 'green' | 'amber' | 'rose' | 'brand' | 'gold'; children: React.ReactNode }) {
  const cls = {
    green: 'bg-emerald-50 text-emerald-700',
    amber: 'bg-amber-50 text-amber-700',
    rose: 'bg-rose-50 text-rose-700',
    brand: 'bg-brand-50 text-brand-700',
    gold: 'bg-gold-500/10 text-gold-600',
  }[tone];
  return <span className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-medium ${cls}`}>{children}</span>;
}
